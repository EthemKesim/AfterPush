import hashlib
import re
from dataclasses import dataclass
from uuid import UUID


APPLICATION_NAME_PATTERN = re.compile(
    r"^[a-z0-9]+(?:-[a-z0-9]+)*$"
)

SUPPORTED_ENVIRONMENTS = frozenset(
    {"dev", "staging", "prod"}
)


def build_project_namespace(
    project_id: UUID,
    environment: str,
) -> str:
    if not isinstance(project_id, UUID):
        raise TypeError("project_id must be a UUID.")

    if environment not in SUPPORTED_ENVIRONMENTS:
        raise ValueError("Unsupported deployment environment")

    return f"ap-{environment}-{project_id}"


@dataclass(frozen=True)
class ArgoCDApplicationIdentity:
    application_name: str
    namespace: str
    gitops_path: str


def build_argocd_application_identity(
    project_id: UUID,
    application_name: str,
    environment: str,
) -> ArgoCDApplicationIdentity:
    """
    Build the identity generated by the project ApplicationSet.

    Must remain consistent with:
    argocd/applications/afterpush-project-applicationset.yaml
    """

    if environment not in SUPPORTED_ENVIRONMENTS:
        raise ValueError("Unsupported deployment environment")

    if not (
        3 <= len(application_name) <= 100
        and APPLICATION_NAME_PATTERN.fullmatch(application_name)
    ):
        raise ValueError("Invalid application name")

    gitops_path = (
        f"gitops/apps/{environment}/"
        f"{project_id}/{application_name}"
    )

    identity_hash = hashlib.sha256(
        gitops_path.encode("utf-8")
    ).hexdigest()[:12]

    return ArgoCDApplicationIdentity(
        application_name=f"ap-{environment}-{identity_hash}",
        namespace=build_project_namespace(project_id, environment),
        gitops_path=gitops_path,
    )
